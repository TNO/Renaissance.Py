"""Guard rail that keeps the copyright notice of `COPYRIGHT.txt` at the top of every tracked file.

`COPYRIGHT.txt` is the single source of truth for the notice. Every git-tracked file carries it as a
comment in the style of its file type: each line prefixed by `#`, or the whole notice in one HTML
comment. The notice comes first, after only the lines that must stay first: a UTF-8 byte order mark,
a shebang, a Python encoding declaration (PEP 263), a Gherkin language line or Markdown front matter.
Exactly one blank line separates the notice from the rest of the file.

`check` reports each file that does not carry the notice exactly; `insert` adds the notice to files
that lack it, and `remove` takes the exact current notice out again. Both preserve the encoding, the
line endings and the presence of a final newline, so `insert` followed by `remove` restores the
original bytes. To change the notice: run `remove`, edit `COPYRIGHT.txt`, and run `insert`.

Files that cannot or must not carry the notice are listed in `EXCLUDED`, and the test inputs, listed
under `[tool.ruff] extend-exclude` in `pyproject.toml`, are never touched. A tracked file of a type
that is neither in `COMMENT_STYLES` nor excluded fails the check, as does an exclusion pattern that
matches no tracked file.

Run `python tools/check_copyright.py check` as CI does, optionally followed by files or directories
to limit the run to.
"""

import argparse
import codecs
import itertools
import re
import shutil
import subprocess
import sys
import tomllib
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, cast

ROOT = Path(__file__).resolve().parents[1]
NOTICE_FILE = ROOT / "COPYRIGHT.txt"
PYPROJECT_FILE = ROOT / "pyproject.toml"


@dataclass(frozen=True)
class CommentStyle:
    """How the notice is written as a comment: each line prefixed by `line`, or the whole notice enclosed by `block`."""

    line: str | None = None
    block: tuple[str, str] | None = None


HASH = CommentStyle(line="#")
HTML = CommentStyle(block=("<!--", "-->"))

# The comment style per file name or suffix; a file name entry wins over a suffix entry.
COMMENT_STYLES: dict[str, CommentStyle] = {
    ".feature": HASH,
    ".gitignore": HASH,
    ".md": HTML,
    ".py": HASH,
    ".toml": HASH,
    ".yml": HASH,
}

# Tracked files that cannot or must not carry the notice, as `PurePath.full_match` patterns, with the reason.
EXCLUDED: dict[str, str] = {
    "**/*.json": "JSON has no comment syntax",
    "**/*.png": "binary image",
    "**/*.pptx": "binary presentation",
    "CLA.md": "legal agreement with its own terms",
    "COPYRIGHT.txt": "the notice itself",
    "LICENSE": "the license text itself",
    "docs/TODO": "plain text without comment syntax",
    "uv.lock": "generated by uv",
}

EXIT_OK = 0
EXIT_VIOLATIONS = 1
EXIT_TOOL_FAILURE = 2

UTF8_BOM = codecs.BOM_UTF8
# UTF-32 LE goes before UTF-16 LE, because it starts with the same two bytes.
UNSUPPORTED_BOMS = (codecs.BOM_UTF32_LE, codecs.BOM_UTF32_BE, codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)
LINE_END = re.compile(rb"\r\n|\r|\n")
DEFAULT_LINE_END = b"\n"
SHEBANG = b"#!"
# PEP 263: the encoding declaration of a Python file, on line 1, or on line 2 below a blank or comment-only line.
CODING = re.compile(rb"[ \t\f]*#.*?coding[:=][ \t]*([-_.a-zA-Z0-9]+)")
BLANK_OR_COMMENT = re.compile(rb"[ \t\f]*(?:#.*)?")
GHERKIN_LANGUAGE = re.compile(rb"[ \t]*#[ \t]*language[ \t]*:")
FRONT_MATTER_OPENING = b"---"
FRONT_MATTER_CLOSINGS = (b"---", b"...")
# The pattern by which Ruff's flake8-copyright (CPY001) recognises a copyright notice.
COPYRIGHT_LIKE = re.compile(r"(?i)Copyright\s+(?:(?:\(C\)|\u00a9)\s+)?\d{4}(?:(?:-|,\s)\d{4})*")
COMMENT_MARKERS = ("<!--", "-->", "/*", "*/", "//", "#", "*")


class FileError(Exception):
    """A file that the tool cannot handle as it is; the message says why."""


@dataclass(frozen=True)
class Analysis:
    """Where the notice belongs in a file, how it is written there, and whether it is present."""

    offset: int
    line_end: bytes
    block: bytes
    present: bool
    problem: str | None


def load_notice(path: Path) -> tuple[str, ...]:
    """Return the lines of the notice in `path`, without trailing empty lines."""
    text = path.read_bytes().decode("utf-8")
    lines = text.splitlines()
    while lines and not lines[-1]:
        lines.pop()
    if not lines or not lines[0] or text.startswith("\ufeff"):
        message = f"{path.name} must start with a non-empty line, without a byte order mark"
        raise ValueError(message)
    if any(line != line.rstrip() for line in lines):
        message = f"{path.name} must not contain trailing whitespace"
        raise ValueError(message)
    return tuple(lines)


def load_test_inputs(path: Path) -> tuple[str, ...]:
    """Return the test-input patterns, the `[tool.ruff] extend-exclude` list of the pyproject file at `path`."""
    with path.open("rb") as file:
        configuration: dict[str, Any] = tomllib.load(file)
    raw: object = configuration.get("tool", {}).get("ruff", {}).get("extend-exclude")
    items = cast("list[object]", raw) if isinstance(raw, list) else None
    patterns = [item for item in items if isinstance(item, str)] if items is not None else []
    if items is None or len(patterns) != len(items):
        message = f"{path.name} must list the test inputs as strings in [tool.ruff] extend-exclude"
        raise ValueError(message)
    return tuple(patterns)


def tracked_files(root: Path, paths: Sequence[Path] = ()) -> list[PurePosixPath]:
    """Return the git-tracked files under `root`, limited to `paths` when given."""
    git = shutil.which("git")
    if git is None:
        message = "git executable not found"
        raise FileNotFoundError(message)
    root = root.resolve()
    pathspecs: list[str] = []
    for path in paths:
        resolved = (root / path).resolve()
        if not resolved.is_relative_to(root):
            message = f"{path} lies outside the repository"
            raise ValueError(message)
        pathspecs.append(resolved.relative_to(root).as_posix())
    command = [git, "ls-files", "-z", "--error-unmatch", "--", *pathspecs]
    result = subprocess.run(command, capture_output=True, cwd=root, check=False)  # noqa: S603 (git with arguments built here)
    if result.returncode != 0:
        message = f"git ls-files failed: {result.stderr.decode('utf-8', errors='replace').strip()}"
        raise ValueError(message)
    return [PurePosixPath(name) for name in result.stdout.decode("utf-8").split("\0") if name]


def is_test_input(path: PurePosixPath, pattern: str) -> bool:
    """Return whether Ruff's exclusion `pattern` excludes `path`, directly or through one of its directories."""
    if "/" not in pattern:
        return any(PurePosixPath(part).full_match(pattern) for part in path.parts)
    return any(candidate.full_match(pattern) for candidate in (path, *path.parents))


def is_excluded(path: PurePosixPath, test_inputs: Iterable[str]) -> bool:
    """Return whether `path` is excluded or a test input."""
    return any(path.full_match(pattern) for pattern in EXCLUDED) or any(is_test_input(path, pattern) for pattern in test_inputs)


def stale_patterns(files: Iterable[PurePosixPath], test_inputs: Iterable[str]) -> list[str]:
    """Return the exclusion and test-input patterns that match none of `files`."""
    files = list(files)
    stale = [pattern for pattern in EXCLUDED if not any(path.full_match(pattern) for path in files)]
    return stale + [pattern for pattern in test_inputs if not any(is_test_input(path, pattern) for path in files)]


def comment_style(path: PurePosixPath) -> CommentStyle | None:
    """Return the comment style for `path`, or None when its file type has none."""
    return COMMENT_STYLES.get(path.name) or COMMENT_STYLES.get(path.suffix)


def render(notice: Sequence[str], style: CommentStyle) -> list[str]:
    """Return the lines of `notice` written as a comment in `style`."""
    if style.block is None:
        marker = style.line or ""
        return [f"{marker} {text}" if text else marker for text in notice]
    opening, closing = style.block
    if any(closing in text for text in notice):
        message = f"the notice must not contain {closing!r}, which would end its comment"
        raise ValueError(message)
    return [opening, *notice, closing]


def line_ending(data: bytes) -> bytes:
    """Return the line ending used in `data`."""
    endings: set[bytes] = set(LINE_END.findall(data))
    if len(endings) > 1:
        message = "mixed line endings"
        raise FileError(message)
    return endings.pop() if endings else DEFAULT_LINE_END


def _lines(data: bytes, start: int) -> list[tuple[int, int, int]]:
    """Return the start, content end and end (after the line ending) of each line of `data` from `start`."""
    lines: list[tuple[int, int, int]] = []
    position = start
    for match in LINE_END.finditer(data, start):
        lines.append((position, match.start(), match.end()))
        position = match.end()
    if position < len(data):
        lines.append((position, len(data), len(data)))
    return lines


def _python_encoding(contents: Sequence[bytes]) -> tuple[int, str]:
    """Return the number of leading lines up to the encoding declaration (0 if absent), and the encoding."""
    for index, content in enumerate(contents[:2]):
        match = CODING.match(content)
        if match:
            return index + 1, match.group(1).decode("ascii")
        if not BLANK_OR_COMMENT.fullmatch(content):
            break
    return 0, "utf-8"


def _front_matter_length(contents: Sequence[bytes]) -> int:
    """Return the number of lines of the Markdown front matter at the start of `contents` (0 if absent)."""
    if not contents or contents[0] != FRONT_MATTER_OPENING:
        return 0
    return next((index + 1 for index in range(1, len(contents)) if contents[index] in FRONT_MATTER_CLOSINGS), 0)


def _check_encoding(encoding: str, *, has_bom: bool) -> None:
    """Fail unless `encoding` is known and ASCII compatible, and agrees with a UTF-8 byte order mark."""
    try:
        name = codecs.lookup(encoding).name
    except LookupError as error:
        message = f"unknown encoding {encoding!r}"
        raise FileError(message) from error
    if has_bom and name != "utf-8":
        message = f"a UTF-8 byte order mark contradicts the encoding declaration {encoding!r}"
        raise FileError(message)
    probe = "#\r\n"
    if probe.encode(name) != probe.encode("ascii"):
        message = f"encoding {encoding!r} is not ASCII compatible"
        raise FileError(message)


def locate(data: bytes, path: PurePosixPath) -> tuple[int, str]:
    """Return the offset in `data` where the notice belongs, and the encoding of the file."""
    if data.startswith(UNSUPPORTED_BOMS):
        message = "UTF-16 and UTF-32 files are not supported"
        raise FileError(message)
    has_bom = data.startswith(UTF8_BOM)
    start = len(UTF8_BOM) if has_bom else 0
    lines = _lines(data, start)
    contents = [data[line_start:content_end] for line_start, content_end, _ in lines]
    leading = 1 if contents and contents[0].startswith(SHEBANG) else 0
    encoding = "utf-8"
    if path.suffix == ".py":
        declaration_lines, encoding = _python_encoding(contents)
        leading = max(leading, declaration_lines)
    elif path.suffix == ".feature" and contents and GHERKIN_LANGUAGE.match(contents[0]):
        leading = 1
    elif path.suffix == ".md":
        leading = max(leading, _front_matter_length(contents))
    _check_encoding(encoding, has_bom=has_bom)
    try:
        data[start:].decode(encoding)
    except UnicodeDecodeError as error:
        message = f"content is not valid {encoding}"
        raise FileError(message) from error
    if not leading:
        return start, encoding
    _, content_end, end = lines[leading - 1]
    if content_end == end:
        message = "the file ends in a line that must precede the notice, without a line ending"
        raise FileError(message)
    return end, encoding


def _strip_markers(line: str) -> str:
    """Return `line` without surrounding whitespace and comment markers."""
    previous = None
    while previous != line:
        previous = line
        line = line.strip()
        for marker in COMMENT_MARKERS:
            line = line.removeprefix(marker).removesuffix(marker)
    return line


def _normalised(lines: Iterable[str]) -> str:
    """Return the non-empty `lines` without comment markers, each line enclosed in newlines."""
    stripped = (_strip_markers(line) for line in lines)
    return "\n" + "".join(f"{line}\n" for line in stripped if line)


def header_comment(text: str, style: CommentStyle) -> list[str]:
    """Return the lines of the comments, in `style`, that open `text`."""
    if style.block is None:
        marker = style.line or ""
        return list(itertools.takewhile(lambda line: not line.strip() or line.lstrip().startswith(marker), text.splitlines()))
    opening, closing = style.block
    comments: list[str] = []
    rest = text.lstrip()
    while rest.startswith(opening):
        end = rest.find(closing, len(opening))
        end = len(rest) if end < 0 else end + len(closing)
        comments.append(rest[:end])
        rest = rest[end:].lstrip()
    return "\n".join(comments).splitlines()


def _follows_too_late(following: bytes, path: PurePosixPath) -> bool:
    """Return whether the line after the notice should have preceded it."""
    first = LINE_END.split(following, maxsplit=1)[0]
    return first.startswith(SHEBANG) or (path.suffix == ".py" and CODING.match(first) is not None)


def _problem_without_notice(data: bytes, text: str, block: bytes, style: CommentStyle, notice: Sequence[str]) -> str | None:
    """Return the problem with a file whose notice is not in place, or None when the notice is simply missing."""
    if block in data:
        return (
            "notice at the wrong position: only a byte order mark, shebang, encoding declaration, "
            "language line or front matter may precede it"
        )
    header = header_comment(text, style)
    if _normalised(notice) in _normalised(header):
        return "notice in the wrong comment style or layout"
    if any(COPYRIGHT_LIKE.search(line) for line in header):
        return "notice modified or outdated: the header holds a copyright notice that differs from COPYRIGHT.txt"
    return None


def analyse(data: bytes, path: PurePosixPath, style: CommentStyle, notice: Sequence[str]) -> Analysis:
    """Return where the notice belongs in the content `data` of the file at `path`, and whether it is there."""
    line_end = line_ending(data)
    offset, encoding = locate(data, path)
    try:
        block = line_end.join(line.encode(encoding) for line in render(notice, style))
    except UnicodeEncodeError as error:
        message = f"the notice cannot be encoded in {encoding}"
        raise FileError(message) from error
    rest = data[offset:]
    framed = block + line_end
    if rest.startswith(framed):
        following = rest[len(framed) :]
        if following and not following.startswith(line_end):
            return Analysis(offset, line_end, block, present=False, problem="notice not followed by a blank line")
        if _follows_too_late(following.removeprefix(line_end), path):
            return Analysis(offset, line_end, block, present=False, problem="notice above a shebang or encoding declaration")
        return Analysis(offset, line_end, block, present=True, problem=None)
    if rest == block:
        return Analysis(offset, line_end, block, present=False, problem="notice not followed by a line ending")
    problem = _problem_without_notice(data, rest.decode(encoding), block, style, notice)
    return Analysis(offset, line_end, block, present=False, problem=problem)


def insert_notice(data: bytes, analysis: Analysis) -> bytes:
    """Return `data` with the notice inserted where `analysis` says it belongs."""
    rest = data[analysis.offset :]
    separator = analysis.line_end if rest else b""
    return data[: analysis.offset] + analysis.block + analysis.line_end + separator + rest


def remove_notice(data: bytes, analysis: Analysis) -> bytes:
    """Return `data` without the notice that `analysis` found, and without the blank line after it."""
    following = data[analysis.offset + len(analysis.block) + len(analysis.line_end) :]
    return data[: analysis.offset] + following.removeprefix(analysis.line_end)


def handle(command: str, path: PurePosixPath, data: bytes, notice: Sequence[str]) -> tuple[bytes, str | None]:
    """Return the content `command` leaves in the file at `path`, and the violation it reports (None if there is none)."""
    style = comment_style(path)
    if style is None:
        return data, "unmapped file type: add it to COMMENT_STYLES or EXCLUDED in tools/check_copyright.py"
    try:
        analysis = analyse(data, path, style, notice)
    except FileError as problem:
        return data, str(problem)
    if analysis.problem is not None:
        return data, analysis.problem
    if command == "insert":
        return (data if analysis.present else insert_notice(data, analysis)), None
    if command == "remove":
        return (remove_notice(data, analysis) if analysis.present else data), None
    return data, None if analysis.present else "notice missing"


def run(command: str, files: Iterable[PurePosixPath], notice: Sequence[str], test_inputs: Sequence[str]) -> tuple[list[str], list[str]]:
    """Apply `command` to the `files` that are not excluded; return the violations and the changes, one line each."""
    violations: list[str] = []
    changes: list[str] = []
    for path in sorted(files):
        if is_excluded(path, test_inputs):
            continue
        file = ROOT / path
        data = file.read_bytes()
        new_data, violation = handle(command, path, data, notice)
        if violation is not None:
            violations.append(f"{path}: {violation}")
        if new_data != data:
            file.write_bytes(new_data)
            changes.append(f"{path}: notice {'inserted' if command == 'insert' else 'removed'}")
    return violations, changes


def main(argv: list[str] | None = None) -> int:
    """Run the copyright guard rail and return its exit code."""
    parser = argparse.ArgumentParser(description="Check, insert or remove the copyright notice of COPYRIGHT.txt in all tracked files.")
    parser.add_argument("command", choices=("check", "insert", "remove"), help="what to do with the notice")
    parser.add_argument("paths", nargs="*", type=Path, help="limit the run to these tracked files or directories")
    args = parser.parse_args(argv)
    command: str = args.command
    paths: list[Path] = args.paths
    try:
        notice = load_notice(NOTICE_FILE)
        for style in set(COMMENT_STYLES.values()):
            render(notice, style)
        test_inputs = load_test_inputs(PYPROJECT_FILE)
        files = tracked_files(ROOT, paths)
        violations, changes = run(command, files, notice, test_inputs)
    except (OSError, ValueError) as error:
        print(f"check_copyright: {error}", file=sys.stderr)  # noqa: T201 (a script reports on stdout and stderr)
        return EXIT_TOOL_FAILURE
    if not paths:
        violations += [f"{pattern}: exclusion pattern matches no tracked file; delete it" for pattern in stale_patterns(files, test_inputs)]
    report = [*changes, *violations]
    if violations:
        report.append(f"Copyright {command} failed: {len(violations)} violation(s); see docs/developer/tools/check-copyright.md.")
    elif command == "check":
        report.append("Copyright check passed.")
    else:
        report.append(f"Copyright {command} passed: {len(changes)} file(s) changed.")
    print("\n".join(report))  # noqa: T201 (a script reports on stdout and stderr)
    return EXIT_VIOLATIONS if violations else EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
